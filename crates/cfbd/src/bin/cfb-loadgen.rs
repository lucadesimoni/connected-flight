//! cfb-loadgen - load generator for cfbd (docs/17).
//!
//! 1. Write a self-contained heavy setup (config, ARINC label table, a
//!    signed edge-app package with many rules, ASCI, ephemeral signing key).
//! 2. Stream cfb-io lines into cfbd.
//!
//! ```text
//! cfb-loadgen setup --dir D [--labels 64] [--channels 4] [--rules 128]
//!                   [--transport 127.0.0.1:7600]
//! cfb-loadgen run --config D/loadtest.toml --seconds 3600 \
//!     [--words-per-sec 11000] [--imu-hz 100] [--pace-ms 0] \
//!     [--storm START:LEN] [--flood START:LEN] [--ground-only] \
//!   | cfbd --config D/loadtest.toml
//! ```
//!
//! * `--words-per-sec`: ARINC 429 words per second over all channels.
//!   4 channels at high speed (100 kbit/s, 36 bit times per word) carry at
//!   most ~11 100 words/s: the physical worst case.
//! * `--storm`: every ARINC parameter goes above its exceedance limit at
//!   once (all edge rules fire), plus IMU Nz spikes.
//! * `--flood`: 4x the word rate and 4x the IMU rate for the window.
//! * `--pace-ms 0`: as fast as cfbd reads (throughput/headroom test);
//!   otherwise sleep between ticks (time compression for end-to-end runs).

use cfb_core::arinc429::{Ssm, Word};
use cfb_core::gnss::make_rmc_gga;
use cfb_core::Config;
use ed25519_dalek::{Signer, SigningKey};
use std::io::{BufWriter, Read, Write};
use std::path::{Path, PathBuf};
use std::time::Duration;

fn arg(args: &[String], name: &str) -> Option<String> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1)).cloned()
}

fn num<T: std::str::FromStr>(args: &[String], name: &str, def: T) -> T {
    arg(args, name).and_then(|v| v.parse().ok()).unwrap_or(def)
}

fn window(args: &[String], name: &str) -> Option<(u64, u64)> {
    let v = arg(args, name)?;
    let (a, b) = v.split_once(':')?;
    Some((a.parse().ok()?, b.parse().ok()?))
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

// ------------------------------------------------------------ setup

fn setup(args: &[String]) -> Result<(), String> {
    let dir = PathBuf::from(arg(args, "--dir").ok_or("--dir required")?);
    let labels: usize = num(args, "--labels", 64);
    let channels: u8 = num(args, "--channels", 4);
    let rules: usize = num(args, "--rules", 128);
    let transport = arg(args, "--transport");
    if !(1..=200).contains(&labels) || !(channels == 2 || channels == 4) {
        return Err("labels 1..200, channels 2 or 4".into());
    }
    let apps = dir.join("apps");
    std::fs::create_dir_all(&apps).map_err(|e| e.to_string())?;

    // Ephemeral key: the run exercises the real signature + ASCI path.
    let mut seed = [0u8; 32];
    std::fs::File::open("/dev/urandom").and_then(|mut f| f.read_exact(&mut seed)).map_err(|e| e.to_string())?;
    let key = SigningKey::from_bytes(&seed);
    let pubhex = hex(key.verifying_key().as_bytes());

    // ARINC label table: params p000.., spread over the channels.
    let mut label_toml = String::new();
    for i in 0..labels {
        label_toml.push_str(&format!(
            "\n[[arinc429.labels]]\nchannel = {}\nlabel = \"{:o}\"\nparam = \"p{i:03}\"\nformat = \"bnr\"\nrange = 2048.0\nsig_bits = 14\n",
            i % channels as usize,
            0o100 + (i / channels as usize)
        ));
    }
    let transport_toml = match &transport {
        Some(g) => format!(
            "\n[transport]\nground = \"{g}\"\nretry_s = 15\n\n[transport.bearers.cellular]\nlocal = \"127.0.0.1:0\"\nnominal_bps = 2000000\nkeepalive_s = 5\ndown_after_s = 20\n"
        ),
        None => String::new(),
    };
    let d = dir.display();
    let cfg = format!(
        r#"# Generated by cfb-loadgen setup - load test only.
[aircraft]
registration = "LOADTEST"
icao24 = "000000"
aircraft_type = "Load test"
bus_voltage = 28

[modules]
arinc429 = {{ channels = {channels}, speed = "high" }}
gnss = true
imu = true
wifi = true
cellular = "4g"
satcom = ["iridium"]

[arinc429]
label_reversed = false
{label_toml}
[imu]
axes = ["+x", "+y", "+z"]
sample_rate_hz = 100.0
engine_vib_g = 0.04
engine_on_s = 5.0
engine_off_s = 10.0
hard_landing_nz = 1.8
turbulence_dnz = 1.0

[links.wifi]
enabled = true
ground_only = true
cost_per_mb = 0.0
min_priority = "bulk"

[links.cellular]
enabled = true
ground_only = true
cost_per_mb = 0.01
min_priority = "bulk"

[links.iridium]
enabled = true
ground_only = false
cost_per_mb = 600.0
min_priority = "high"
flight_budget_bytes = 65536

[queue]
max_bytes = 67108864
snapshot_path = "{d}/queue.bin"
snapshot_interval_s = 60

[reporting]
position_interval_air_s = 30
position_interval_ground_s = 60
position_ttl_s = 0

[update]
hw_part_number = "CFB-HW-LOAD"
min_supply_v = 11.5
trusted_keys = ["{pubhex}"]

[edge]
asci = "{d}/apps-asci.toml"
app_dirs = ["{d}/apps"]

[maintenance]
status_path = "{d}/status.json"
{transport_toml}"#
    );
    Config::from_toml(&cfg).map_err(|e| format!("generated config invalid: {e}"))?;
    std::fs::write(dir.join("loadtest.toml"), &cfg).map_err(|e| e.to_string())?;

    // Edge app: one exceedance rule per parameter (up to --rules), plus
    // trend rules over groups of 8 parameters, plus the flight summary.
    let mut app = String::from("[app]\nid = \"load-edge\"\npart_number = \"CFB-APP-9999\"\nversion = \"1.0.0\"\n");
    for i in 0..rules {
        app.push_str(&format!(
            "\n[[exceedance]]\nid = \"EXC_{i:03}\"\nparam = \"p{:03}\"\nabove = 900.0\nfor_s = 2\nwhen = \"any\"\npriority = \"high\"\n",
            i % labels
        ));
    }
    for g in 0..(labels / 8).max(1) {
        let params: Vec<String> = (0..8).map(|k| format!("\"p{:03}\"", (g * 8 + k) % labels)).collect();
        app.push_str(&format!(
            "\n[[trend]]\nid = \"TR_{g:02}\"\nparams = [{}]\nstable_s = 60\nmax_per_flight = 3\npriority = \"normal\"\nstable = [ {{ param = \"p{:03}\", band = 200.0 }} ]\n",
            params.join(", "),
            g * 8 % labels
        ));
    }
    app.push_str("\n[summary]\nenabled = true\n");
    cfb_core::edge::AppPackage::parse(app.as_bytes()).map_err(|e| format!("generated app invalid: {e}"))?;
    let asci = "issue = 1\n[[entries]]\npart_number = \"CFB-APP-9999\"\nversion = \"1.0.0\"\nhw_part_number = \"CFB-HW-LOAD\"\n";
    let w = |p: &Path, b: &[u8]| std::fs::write(p, b).map_err(|e| e.to_string());
    w(&apps.join("load-edge.toml"), app.as_bytes())?;
    w(&apps.join("load-edge.toml.sig"), &key.sign(app.as_bytes()).to_bytes())?;
    w(&dir.join("apps-asci.toml"), asci.as_bytes())?;
    w(&dir.join("apps-asci.toml.sig"), &key.sign(asci.as_bytes()).to_bytes())?;
    eprintln!(
        "cfb-loadgen: setup in {d}: {labels} ARINC labels on {channels} channels, {rules} exceedance rules, {} trend rules, signed",
        (labels / 8).max(1)
    );
    Ok(())
}

// ------------------------------------------------------------ run

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> f32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 40) as f32 / (1u64 << 24) as f32 * 2.0 - 1.0
    }
}

fn run(args: &[String]) -> Result<(), String> {
    let cfg_path = arg(args, "--config").ok_or("--config required")?;
    let cfg = Config::from_toml(&std::fs::read_to_string(&cfg_path).map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
    let seconds: u64 = num(args, "--seconds", 600);
    let wps: usize = num(args, "--words-per-sec", 11_000);
    let imu_hz: usize = num(args, "--imu-hz", 100);
    let pace = Duration::from_millis(num(args, "--pace-ms", 0));
    let storm = window(args, "--storm");
    let flood = window(args, "--flood");
    let ground_only = args.iter().any(|a| a == "--ground-only");
    let in_win = |w: Option<(u64, u64)>, t: u64| w.is_some_and(|(s, l)| t >= s && t < s + l);

    let labels: Vec<(u8, u16, String)> = cfg
        .arinc429
        .labels
        .iter()
        .filter_map(|l| Some((l.channel.unwrap_or(0), u16::from_str_radix(&l.label, 8).ok()?, l.param.clone())))
        .collect();
    let hw = cfg.modules.expected_ids().join(",");
    let mut out = BufWriter::with_capacity(1 << 20, std::io::stdout().lock());
    let mut rng = Rng(0x9E37_79B9_7F4A_7C15);
    let mut line = String::with_capacity(256 * 1024);
    let mut total_words: u64 = 0;
    for t in 0..seconds {
        let airborne = !ground_only && t >= 60;
        let flooding = in_win(flood, t);
        let storming = in_win(storm, t);
        line.clear();
        line.push_str(&format!(
            "t={t} wow={} eng=1 maint=0 v=27.8 rfsw=- pfail=0",
            if airborne { 0 } else { 1 }
        ));
        if t == 0 {
            line.push_str(&format!(" hw={hw}"));
        }
        // GNSS (own receiver).
        let gs = if airborne { 140.0 } else { 0.0 };
        for s in make_rmc_gga(47.0 + t as f64 * 1e-4, 8.3, gs, 90.0, 8500.0, (36_000 + t) as u32) {
            line.push_str(" nmea=");
            line.push_str(&s);
        }
        // IMU samples (g), vibration noise; Nz spikes during a storm.
        let m = if flooding { imu_hz * 4 } else { imu_hz };
        if m > 0 {
            line.push_str(" imu=");
            for i in 0..m {
                let nz = if storming && i % 25 == 0 { 2.4 } else { 1.0 };
                if i > 0 {
                    line.push(';');
                }
                line.push_str(&format!("{:.4},{:.4},{:.4}", 0.08 * rng.next(), 0.08 * rng.next(), -nz + 0.08 * rng.next()));
            }
        }
        // Link state (used when the config has no [transport]).
        line.push_str(if airborne {
            " link.wifi=down link.cellular=down link.iridium=up:2400"
        } else {
            " link.wifi=down link.cellular=up:2000000 link.iridium=up:2400"
        });
        // ARINC 429 last (input.rs order rule): round-robin over the label table.
        let n = if flooding { wps * 4 } else { wps };
        if !labels.is_empty() && n > 0 {
            line.push_str(" a429=");
            for k in 0..n {
                let (ch, lab, _) = &labels[k % labels.len()];
                let base = 500.0 + 100.0 * ((t as f64 / 30.0) + k as f64).sin();
                let v = if storming { 950.0 } else { base };
                let w = Word::encode_bnr(*lab, 0, v, 2048.0, 14, Ssm::Normal);
                if k > 0 {
                    line.push(',');
                }
                line.push_str(&format!("{ch}:{:08x}", w.0));
            }
            total_words += n as u64;
        }
        line.push('\n');
        if out.write_all(line.as_bytes()).is_err() {
            return Ok(()); // cfbd stopped reading
        }
        if !pace.is_zero() {
            let _ = out.flush();
            std::thread::sleep(pace);
        }
    }
    let _ = out.flush();
    eprintln!("cfb-loadgen: {seconds} ticks, {total_words} ARINC words, last line {} bytes", line.len());
    Ok(())
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let r = match args.get(1).map(String::as_str) {
        Some("setup") => setup(&args),
        Some("run") => run(&args),
        _ => Err("usage: cfb-loadgen setup --dir D [...] | run --config D/loadtest.toml [...]".into()),
    };
    if let Err(e) = r {
        eprintln!("cfb-loadgen: {e}");
        std::process::exit(2);
    }
}
